def _require_cuda() -> None:
    import torch

    if not torch.cuda.is_available():
        raise RuntimeError("CUDA is unavailable; refusing to start the GPU replay")
    if torch.cuda.device_count() < 1:
        raise RuntimeError("CUDA reports no devices; refusing to start the GPU replay")


def _make_column(value: int, rows: int) -> "cudf.Series":
    import cudf
    import cupy as cp

    values = cp.full(rows, value, dtype=cp.int64)
    result = cudf.Series(values)
    if int(result._column.data.ptr) != int(values.data.ptr):
        raise RuntimeError("cuDF copied the CuPy allocation instead of adopting it")
    return result


def _sum_column(column: "cudf.Series") -> TaskValue:
    from numba import cuda

    value = int(column.sum())
    cuda.synchronize()
    identity = _worker_identity()
    return {"value": value, "worker": identity["worker"], "pid": identity["pid"]}


def _run_upstream_candidate(candidate_path: str, expected_source: bytes, rows: int) -> None:
    import torch

    path = Path(candidate_path)
    if path.read_bytes() != expected_source:
        raise RuntimeError("worker candidate source differs from the reviewed input")

    module_name = f"opgate_e6_upstream_q03_{os.getpid()}"
    spec = importlib.util.spec_from_file_location(module_name, path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot import upstream candidate: {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[module_name] = module
    spec.loader.exec_module(module)

    device = torch.device("cuda")
    orderkey = torch.arange(1, rows + 1, dtype=torch.int64, device=device)
    price = torch.full((rows,), 2.0, dtype=torch.float64, device=device)
    discount = torch.full((rows,), 0.5, dtype=torch.float64, device=device)
    shipdate = torch.full((rows,), SHIPDATE_VALUE_DAYS, dtype=torch.int32, device=device)
    orderdate = torch.full((rows,), ORDERDATE_VALUE_DAYS, dtype=torch.int32, device=device)
    shippriority = torch.zeros(rows, dtype=torch.int32, device=device)

    module._query_core(
        orderkey,
        price,
        discount,
        shipdate,
        orderdate,
        shippriority,
        SHIPDATE_LO_DAYS,
        ORDERDATE_HI_DAYS,
        10,
    )
    torch.cuda.synchronize()
    raise RuntimeError("the pinned candidate returned without the recorded illegal memory access")


def _synchronize_worker() -> WorkerTask:
    from numba import cuda

    cuda.synchronize()
    identity = _worker_identity()
    return {"worker": identity["worker"], "pid": identity["pid"]}


def _scheduler_observation(dask_scheduler: "Scheduler", task_key: str) -> SchedulerObservation:
    task = dask_scheduler.tasks[task_key]
    dependencies: list[str] = []
    for dependency in task.dependencies:
        key = dependency.key
        if not isinstance(key, str):
            raise TypeError(f"task key is not a string: {key!r}")
        dependencies.append(key)
    return {
        "task": task_key,
        "dependencies": sorted(dependencies),
        "clients": sorted(dask_scheduler.clients),
    }


def _wait_without_gathering(client: "Client", future: "Future[cudf.Series]") -> None:
    from distributed.client import _wait

    client.sync(_wait, [future])
    if future.status == "error":
        error = future.exception()
        if error is None:
            raise RuntimeError(f"task {future.key} failed without an exception")
        raise error


def _start_deployment() -> tuple["LocalCUDACluster", "Client", "Client", str]:
    import logging

    from dask_cuda import LocalCUDACluster
    from distributed import Client

    cluster = LocalCUDACluster(
        CUDA_VISIBLE_DEVICES="0",
        n_workers=1,
        threads_per_worker=1,
        rmm_pool_size=POOL_BYTES,
        rmm_maximum_pool_size=POOL_BYTES,
        device_memory_limit=0,
        dashboard_address=None,
        silence_logs=logging.ERROR,
    )
    client_a = Client(cluster, name="tenant-a", set_as_default=False)
    client_b = Client(cluster, name="tenant-b", set_as_default=False)
    client_a.wait_for_workers(1)
    workers = sorted(client_a.scheduler_info()["workers"])
    if len(workers) != 1:
        raise RuntimeError(f"expected one shared worker, found {workers}")
    return cluster, client_a, client_b, workers[0]


def _error_record(error: BaseException | None) -> ErrorRecord | None:
    if error is None:
        return None
    return {"type": type(error).__name__, "message": str(error)}


def _close_deployment(cluster: "LocalCUDACluster", client_a: "Client", client_b: "Client") -> None:
    errors: list[Exception] = []
    for resource in (client_a, client_b, cluster):
        try:
            resource.close(timeout=10)
        except Exception as error:  # cleanup follows a deliberately poisoned context
            errors.append(error)
    if errors:
        raise RuntimeError(
            "deployment cleanup failed: " + "; ".join(str(error) for error in errors)
        )


def blast_radius_case(upstream: Path) -> BlastRadius:
    provenance = verify_upstream(upstream)
    _require_cuda()
    candidate_path = str(upstream.resolve() / CANDIDATE_REL)
    candidate_source = Path(candidate_path).read_bytes()
    cluster, client_a, client_b, worker = _start_deployment()
    try:
        b_key = "tenant-b-live-column"
        candidate_key = "tenant-a-upstream-llm-kernel"

        tenant_b = client_b.submit(
            _make_column,
            1,
            TENANT_B_ROWS,
            key=b_key,
            pure=False,
        )
        _wait_without_gathering(client_b, tenant_b)
        identity_a = client_a.submit(
            _worker_identity,
            key="tenant-a-worker-identity",
            pure=False,
        ).result()
        identity_b = client_b.submit(
            _worker_identity,
            key="tenant-b-worker-identity",
            pure=False,
        ).result()
        baseline = client_b.submit(
            _sum_column,
            tenant_b,
            key="tenant-b-baseline-sum",
            pure=False,
        ).result()

        candidate_future = client_a.submit(
            _run_upstream_candidate,
            candidate_path,
            candidate_source,
            CANDIDATE_ROWS,
            key=candidate_key,
            pure=False,
        )
        candidate_error: BaseException | None = None
        try:
            candidate_future.result()
        except BaseException as error:
            candidate_error = error
        schedule: SchedulerObservation = client_a.run_on_scheduler(
            _scheduler_observation,
            task_key=candidate_key,
        )

        tenant_b_after: TaskValue | None = None
        tenant_b_error: BaseException | None = None
        try:
            tenant_b_after = client_b.submit(
                _sum_column,
                tenant_b,
                key="tenant-b-sum-after-llm-kernel",
                pure=False,
            ).result()
        except BaseException as error:
            tenant_b_error = error

        synchronize_error: BaseException | None = None
        try:
            client_b.submit(
                _synchronize_worker,
                key="tenant-b-synchronize-after-llm-kernel",
                pure=False,
            ).result()
        except BaseException as error:
            synchronize_error = error

        candidate_message = str(candidate_error).lower() if candidate_error is not None else ""
        success = (
            client_a.id != client_b.id
            and identity_a["worker"] == identity_b["worker"] == baseline["worker"] == worker
            and identity_a["pid"] == identity_b["pid"] == baseline["pid"]
            and baseline["value"] == TENANT_B_ROWS
            and schedule["dependencies"] == []
            and candidate_error is not None
            and "illegal memory access" in candidate_message
            and tenant_b_after is None
            and tenant_b_error is not None
            and synchronize_error is not None
        )
        return {
            "experiment": "E6b: upstream LLM kernel on a shared cuDF worker",
            "success": success,
            "provenance": provenance,
            "clients": {"tenant_a": client_a.id, "tenant_b": client_b.id},
            "shared_worker": worker,
            "tenant_a_before": identity_a,
            "tenant_b_before": identity_b,
            "tenant_b_baseline": baseline,
            "candidate_rows": CANDIDATE_ROWS,
            "candidate_schedule": schedule,
            "candidate_error": _error_record(candidate_error),
            "tenant_b_after": tenant_b_after,
            "tenant_b_error": _error_record(tenant_b_error),
            "synchronize_error": _error_record(synchronize_error),
            "meaning": (
                "A commit-pinned model output generated for a normal TPC-H request had no B "
                "data dependency, yet its recorded autotuning defect poisoned the shared "
                "worker context and prevented B's previously valid cuDF reduction."
            ),
        }
    finally:
        _close_deployment(cluster, client_a, client_b)


def _emit(result: Result) -> None:
    print(RESULT_PREFIX + json.dumps(result, sort_keys=True), flush=True)


def _succeeded(returncode: int, parsed: dict[str, object] | None) -> bool:
    if returncode != 0 or parsed is None:
        return False
    success = parsed["success"]
    if not isinstance(success, bool):
        raise TypeError(f"the child's success is not a boolean: {success!r}")
    return success


def _run_blast_child(upstream: Path, timeout: int) -> ChildRun | ChildTimeout:
    command = [
        sys.executable,
        "-m",
        module_of(__file__),
        "blast-child",
        "--upstream",
        str(upstream.resolve()),
    ]
    try:
        completed = subprocess.run(
            command,
            capture_output=True,
            text=True,
            timeout=timeout,
            check=False,
            env=os.environ.copy(),
        )
    except subprocess.TimeoutExpired as error:
        stdout = (
            error.stdout.decode(errors="replace")
            if isinstance(error.stdout, bytes)
            else error.stdout
        )
        stderr = (
            error.stderr.decode(errors="replace")
            if isinstance(error.stderr, bytes)
            else error.stderr
        )
        return {
            "case": "blast-radius",
            "returncode": None,
            "result": None,
            "stdout": stdout or "",
            "stderr": stderr or "",
            "timeout_seconds": timeout,
            "success": False,
        }
    parsed: dict[str, object] | None = None
    for line in completed.stdout.splitlines():
        if line.startswith(RESULT_PREFIX):
            parsed = _object(json.loads(line.removeprefix(RESULT_PREFIX)))
    return {
        "case": "blast-radius",
        "returncode": completed.returncode,
        "result": parsed,
        "stdout": completed.stdout if parsed is None else "",
        "stderr": completed.stderr,
        "success": _succeeded(completed.returncode, parsed),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "case",
        choices=("audit", "blast-radius", "blast-child", "all"),
        nargs="?",
        default="all",
    )
    parser.add_argument(
        "--upstream",
        type=Path,
        required=True,
        help=f"DataKernelBench checkout at commit {UPSTREAM_COMMIT}",
    )
    parser.add_argument("--timeout", type=int, default=600)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()

    if args.case == "audit":
        result: Result = audit_artifact(args.upstream)
    elif args.case == "blast-child":
        result = blast_radius_case(args.upstream)
    elif args.case == "blast-radius":
        result = _run_blast_child(args.upstream, args.timeout)
    else:
        audit = audit_artifact(args.upstream)
        blast = _run_blast_child(args.upstream, args.timeout)
        result = AllCases(
            experiment="E6: independent LLM-generated database kernel",
            success=audit["success"] and blast["success"],
            cases=[audit, blast],
        )

    _emit(result)
    if args.output is not None:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n")
    return 0 if result["success"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
