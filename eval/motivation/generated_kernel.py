"""E6: audit and replay an independently generated database kernel.

The audit reads the public DataKernelBench artifact at one pinned commit.  It
checks the complete 10-model, 4-setting, 22-query matrix and the recorded bytes of the
prompt, model output, and recorded failure used by the replay.

The replay gives two named Dask clients one dask-cuda worker.  Client B keeps a
live cuDF column and verifies it.  Client A then runs the unchanged first-round
Triton module generated by Claude Opus 4.7 for TPC-H Q3.  The module's autotuned
stream-compaction kernel mutates one output counter without resetting it between
autotuning configurations; upstream recorded an illegal memory access.  The
replay checks whether that ordinary generated module poisons the CUDA context
and prevents B's previously valid cuDF reduction from running.

The existing E1 experiments are independent and remain unchanged.
"""

