def _object(value: object) -> dict[str, object]:
    if not isinstance(value, dict):
        raise TypeError(f"expected a JSON object, found {value!r}")
    return value


def _string(record: dict[str, object], key: str) -> str:
    value = record[key]
    if not isinstance(value, str):
        raise TypeError(f"{key} is not a string: {value!r}")
    return value


def _integer(record: dict[str, object], key: str) -> int:
    value = record[key]
    if not isinstance(value, int) or isinstance(value, bool):
        raise TypeError(f"{key} is not an integer: {value!r}")
    return value


def _rounds(result: dict[str, object]) -> list[dict[str, object]]:
    rounds = result.get("rounds", [])
    if not isinstance(rounds, list):
        raise TypeError(f"rounds is not a list: {rounds!r}")
    return [_object(record) for record in rounds]


def _message(round_record: dict[str, object]) -> str | None:
    message = round_record.get("message")
    if message is not None and not isinstance(message, str):
        raise TypeError(f"round message is not a string: {message!r}")
    return message


def _git_head(upstream: Path) -> str:
    completed = subprocess.run(
        ["git", "-C", str(upstream), "rev-parse", "HEAD"],
        check=True,
        capture_output=True,
        text=True,
    )
    return completed.stdout.strip()


def verify_upstream(upstream: Path) -> Provenance:
    upstream = upstream.resolve()
    if not upstream.is_dir():
        raise FileNotFoundError(f"DataKernelBench checkout does not exist: {upstream}")

    commit = _git_head(upstream)
    if commit != UPSTREAM_COMMIT:
        raise RuntimeError(f"expected DataKernelBench {UPSTREAM_COMMIT}, found {commit}")

    for relative in VERIFIED_FILES:
        path = upstream / relative
        if not path.is_file():
            raise FileNotFoundError(f"required upstream artifact is missing: {path}")
        recorded = subprocess.run(
            ["git", "-C", str(upstream), "show", f"{commit}:{relative}"],
            check=True,
            capture_output=True,
        ).stdout
        if path.read_bytes() != recorded:
            raise RuntimeError(f"upstream file differs from the selected commit: {relative}")

    run = _object(json.loads((upstream / CANDIDATE_RUN_REL).read_text()))
    if run.get("model") != "aws/claude-opus-4-7":
        raise RuntimeError(f"unexpected model metadata: {run.get('model')!r}")
    if (run.get("framework"), run.get("level")) != ("triton", "core"):
        raise RuntimeError("candidate run is not the pinned Triton/core setting")

    result = _object(json.loads((upstream / CANDIDATE_RESULT_REL).read_text()))
    rounds = _rounds(result)
    if len(rounds) != 1:
        raise RuntimeError(f"expected one candidate round, found {len(rounds)}")
    first = rounds[0]
    if first.get("correctness") != "error_run_candidate":
        raise RuntimeError(f"unexpected candidate result: {first.get('correctness')!r}")
    if "illegal memory access" not in (_message(first) or "").lower():
        raise RuntimeError("pinned upstream result is no longer an illegal-memory-access record")

    source = (upstream / CANDIDATE_REL).read_text()
    witnesses = (
        "@triton.autotune(",
        "for bs in [2048, 4096, 8192]",
        "for w in [4, 8]",
        "for s in [2, 4]",
        'key=["n_elements"]',
        "base = tl.atomic_add(counter_ptr, n_keep)",
        "tl.store(out_lk_ptr + write_idx, lk, mask=keep)",
        "out_lk = torch.empty(n, dtype=torch.int64, device=device)",
        "counter = torch.zeros(1, dtype=torch.int32, device=device)",
    )
    missing = [witness for witness in witnesses if witness not in source]
    if missing:
        raise RuntimeError(f"candidate no longer contains static witnesses: {missing}")
    decorator = source[source.index("@triton.autotune(") : source.index("@triton.jit")]
    if "reset_to_zero" in decorator or "restore_value" in decorator:
        raise RuntimeError("candidate now resets mutated autotuning state")

    return {
        "url": UPSTREAM_URL,
        "commit": commit,
        "verified_files": [str(p) for p in VERIFIED_FILES],
        "candidate": {
            "model": _string(run, "model"),
            "framework": _string(run, "framework"),
            "level": _string(run, "level"),
            "benchmark": _string(run, "benchmark"),
            "scale_factor": _integer(run, "scale_factor"),
            "query": _string(result, "query"),
            "round": _integer(first, "round"),
            "recorded_message": _string(first, "message"),
            "generated_at": _string(_object(result["timing"]), "started_at"),
            "source": str(CANDIDATE_REL),
            "autotune_configurations": 12,
            "mutated_state_reset": False,
            "minimum_state_replay": {
                "rows_passing_predicate": CANDIDATE_ROWS,
                "allocated_output_indices": [0, CANDIDATE_ROWS - 1],
                "configuration_1_write_indices": [0, CANDIDATE_ROWS - 1],
                "configuration_2_write_indices": [CANDIDATE_ROWS, 2 * CANDIDATE_ROWS - 1],
                "maximum_write_index_after_12_single_runs": 12 * CANDIDATE_ROWS - 1,
                "first_out_of_bounds_configuration": 2,
            },
            "static_witness": (
                "The autotuned compaction kernel increments counter_ptr and uses the returned "
                "base to index n-element outputs, but its autotune decorator does not reset "
                "counter_ptr between configurations."
            ),
        },
    }


def _fault_kind(round_record: dict[str, object]) -> FaultKind | None:
    message = (_message(round_record) or "").lower()
    if "illegal memory access" in message or "cudaerrorillegaladdress" in message:
        return "illegal_address"
    if "device-side assert triggered" in message or "cudaerrorassert" in message:
        return "device_assert"
    if (
        "out of memory" in message
        or "out_of_memory" in message
        or "cudaerrormemoryallocation" in message
    ):
        return "out_of_memory"
    return None


def audit_artifact(upstream: Path) -> ArtifactAudit:
    provenance = verify_upstream(upstream)
    root = upstream.resolve() / ARTIFACT_ROOT
    actual_models = tuple(sorted(path.name for path in root.iterdir() if path.is_dir()))
    if actual_models != MODELS:
        raise RuntimeError(f"unexpected model matrix: {actual_models}")

    missing: list[RunKey] = []
    records: list[tuple[RunKey, dict[str, object]]] = []
    for model in MODELS:
        for framework in FRAMEWORKS:
            for level in LEVELS:
                for query in QUERIES:
                    key = (model, framework, level, query)
                    path = root / model / framework / level / "queries" / query / "results.json"
                    if not path.is_file():
                        missing.append(key)
                        continue
                    records.append((key, _object(json.loads(path.read_text()))))

    if tuple(missing) != MISSING_WORKER_CRASHES:
        raise RuntimeError(f"unexpected missing result files: {missing}")

    round_1_status: Counter[str] = Counter()
    round_1_correctness: Counter[str] = Counter()
    round_1_faults: Counter[FaultKind] = Counter()
    all_round_faults: Counter[FaultKind] = Counter()
    all_round_correctness: Counter[str] = Counter()
    first_pass_round: Counter[str] = Counter()
    round_1_fault_records: list[FaultRecord] = []
    eventual_passed = 0
    eventual_correct = 0

    for key, data in records:
        eventual_passed += int(bool(data.get("passed")))
        eventual_correct += int(bool(data.get("correct")))
        rounds = _rounds(data)
        if not rounds:
            raise RuntimeError(f"result without rounds: {data.get('query')}")
        first = rounds[0]
        round_1_status[str(first.get("status"))] += 1
        round_1_correctness[str(first.get("correctness"))] += 1
        first_fault = _fault_kind(first)
        if first_fault is not None:
            round_1_faults[first_fault] += 1
            round_1_fault_records.append(
                {
                    "run": "/".join(key),
                    "kind": first_fault,
                    "message": _message(first),
                }
            )
        passing = next(
            (record["round"] for record in rounds if record.get("status") == "pass"),
            None,
        )
        if passing is not None:
            first_pass_round[str(passing)] += 1
        for record in rounds:
            all_round_correctness[str(record.get("correctness"))] += 1
            fault = _fault_kind(record)
            if fault is not None:
                all_round_faults[fault] += 1

    round_1_correctness["worker_crash"] = len(MISSING_WORKER_CRASHES)
    runtime_errors = (
        round_1_correctness["error_run_candidate"] + round_1_correctness["worker_crash"]
    )
    wrong_output = (
        round_1_correctness["mismatch_values"]
        + round_1_correctness["mismatch_rows"]
        + round_1_correctness["mismatch_columns"]
    )
    generation_errors = round_1_status["error_extract"] + round_1_status["error_llm"]

    observed: AuditCounts = {
        "runs": len(records) + len(missing),
        "result_files": len(records),
        "eventually_passed": eventual_passed,
        "eventually_correct": eventual_correct,
        "round_1_runtime_errors_including_worker_crashes": runtime_errors,
        "round_1_compile_or_import_errors": round_1_correctness["error_load_candidate"],
        "round_1_wrong_output": wrong_output,
        "round_1_generation_or_extraction_errors": generation_errors,
        "round_1_explicit_illegal_address_records": round_1_faults["illegal_address"],
    }
    if observed != EXPECTED_AUDIT:
        raise RuntimeError(f"artifact counts differ from the pinned audit: {observed}")

    return {
        "experiment": "E6a: independent DataKernelBench artifact audit",
        "success": True,
        "provenance": provenance,
        "matrix": {
            "models": list(MODELS),
            "frameworks": list(FRAMEWORKS),
            "levels": list(LEVELS),
            "queries": len(QUERIES),
            "expected_runs": 880,
            "result_files": len(records),
            "imputed_worker_crashes": ["/".join(key) for key in missing],
        },
        "counts": observed,
        "round_1_status": dict(sorted(round_1_status.items())),
        "round_1_correctness": dict(sorted(round_1_correctness.items())),
        "round_1_explicit_gpu_faults": dict(sorted(round_1_faults.items())),
        "round_1_explicit_gpu_fault_records": round_1_fault_records,
        "models_with_round_1_illegal_address": sorted(
            {
                record["run"].split("/", 1)[0]
                for record in round_1_fault_records
                if record["kind"] == "illegal_address"
            }
        ),
        "all_round_correctness": dict(sorted(all_round_correctness.items())),
        "all_round_explicit_gpu_faults": dict(sorted(all_round_faults.items())),
        "first_passing_round": dict(
            sorted(first_pass_round.items(), key=lambda item: int(item[0]))
        ),
        "meaning": (
            "A public 2026 artifact records generated CUDA/Triton database modules from ten "
            "models. Ten first-round modules explicitly hit illegal GPU addresses, and two "
            "additional first-round workers crashed before writing results. The selected "
            "Claude Opus TPC-H Q3 output is commit-pinned and was generated from an ordinary "
            "SQL optimization request."
        ),
    }


