"""Write every CSV file, generated table, and number of the paper from the records."""

import argparse
import os
import tempfile
from pathlib import Path

from eval.export import implementation, prologue, rq1, rq2, rq3, rq4
from eval.export.corpus import REGISTRATION, corpus
from eval.export.records import DATA, FIGURES, ROOT, Numbers, output_to


def _numbers(parts: list[Numbers]) -> str:
    """`numbers.tex`: one macro per number that the paper's text cites."""
    merged: Numbers = {}
    for part in parts:
        repeated = merged.keys() & part.keys()
        if repeated:
            raise ValueError(f"numbers named twice: {sorted(repeated)}")
        merged |= part
    for name in merged:
        if not name.isalpha():
            raise ValueError(f"{name}: a LaTeX macro name has letters only")
    lines = [f"\\newcommand{{\\{name}}}{{{value}}}" for name, value in sorted(merged.items())]
    return (
        "% generated by `python -m eval.export` from the records; do not edit\n"
        + "\n".join(lines)
        + "\n"
    )


def generate(registration: Path) -> None:
    """Validate and generate everything before replacing any published artifact."""
    kernels = corpus(registration)
    with tempfile.TemporaryDirectory(prefix=".export-", dir=FIGURES) as temporary:
        stage = Path(temporary)
        with output_to(stage):
            parts = [
                rq1.export(kernels),
                rq2.export(kernels),
                rq3.export(),
                rq4.export(kernels),
                implementation.export(),
                prologue.export(),
            ]
            (stage / "numbers.tex").write_text(_numbers(parts))
        generated = {p.relative_to(stage) for p in stage.rglob("*") if p.is_file()}
        for relative in sorted(generated):
            target = FIGURES / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            os.replace(stage / relative, target)
        for stale in DATA.glob("*.csv"):
            if stale.relative_to(FIGURES) not in generated:
                stale.unlink()
    for path in sorted(DATA.glob("*.csv")):
        print(path.relative_to(ROOT))


def main() -> None:
    argparse.ArgumentParser(description=__doc__).parse_args()
    generate(REGISTRATION)


if __name__ == "__main__":
    main()
